public class Student {
    String name;
    String _class;
    String school;
    String guardianName;
    String phone;
    String email;
    double payment;

    Student(String name, String _class, String school, String guardianName, String phone, String email, double payment) {
        this.name = name;
        this._class = _class;
        this.school = school;
        this.guardianName = guardianName;
        this.phone = phone;
        this.email = email;
        this.payment = payment;
    }
}
